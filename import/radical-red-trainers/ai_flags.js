#!/usr/bin/env node
'use strict';
/*
 * Generates src/js/data/trainer_ai.js: each trainer's AI flags (CFRU: bit 0 avoid bad moves,
 * bit 1 semi smart, bit 2 look for good moves), read from the Radical Red 4.1 ROM, for the
 * Battle tab's likely-move estimate (js/trainer_ai.js).
 *
 * Usage (after `node build`):  node import/radical-red-trainers/ai_flags.js <Radical Red .gba>
 *
 * Radical Red keeps its boss teams in tables of its own (60-byte entries naming a FireRed trainer
 * id); the flags are that trainer's in gTrainers. Each fight in src/js/data/trainers/<mode>.js is
 * matched to a table entry by trainer name and team (most of the team's species in common).
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '../..');
const OUTPUT = path.join(ROOT, 'src/js/data/trainer_ai.js');
const ROM_BASE = 0x08000000;
const G_TRAINERS = 0x23eac8; // 40-byte entries; the name at +4, aiFlags at +0x1C
const BOSS_TABLES = {normal: [[0x11259b4, 40], [0x1126318, 108]], hardcore: [[0x112c98c, 153]]};
const BOSS_ENTRY = 60;
const PARTY_MON = 28;

function load(file, name) {
	const context = {};
	vm.createContext(context);
	vm.runInContext(fs.readFileSync(path.join(ROOT, file), 'utf8') + ';this.value = ' + name, context);
	return context.value;
}

function main(romFile) {
	const rom = fs.readFileSync(romFile);
	const species = load('src/js/data/radical_red_save_data.js', 'RADICAL_RED_SAVE_DATA').species;
	const text = offset => {
		let out = '';
		for (let c = rom[offset]; c !== 0xFF; c = rom[++offset]) {
			out += c >= 0xBB && c <= 0xD4 ? String.fromCharCode(65 + c - 0xBB) :
				c >= 0xD5 && c <= 0xEE ? String.fromCharCode(97 + c - 0xD5) : c === 0xAD ? '.' : ' ';
		}
		return out.trim();
	};
	const base = name => String(name || '').split('-')[0].toLowerCase();
	const out = {};
	for (const mode of Object.keys(BOSS_TABLES)) {
		const entries = [];
		for (const [start, count] of BOSS_TABLES[mode]) {
			for (let k = 0; k < count; k++) {
				const entry = start + k * BOSS_ENTRY;
				// The party size sits in the next slot: the entries are misaligned by one field.
				const size = rom.readUInt32LE(entry + BOSS_ENTRY + 0x18);
				const trainerId = rom.readUInt32LE(entry + 0x30);
				const party = rom.readUInt32LE(entry + 0x38) - ROM_BASE;
				if (trainerId >= 743 || party < 0 || party + size * PARTY_MON > rom.length) continue;
				const trainer = G_TRAINERS + trainerId * 40;
				const team = new Set();
				for (let i = 0; i < size; i++) team.add(base(species[rom.readUInt16LE(party + i * PARTY_MON)]));
				entries.push({name: text(trainer + 4).toLowerCase(), flags: rom.readUInt32LE(trainer + 0x1C), team});
			}
		}
		out[mode] = {};
		let matched = 0;
		const order = load('src/js/data/trainers/' + mode + '.js', 'TRAINER_ORDER');
		for (const fight of order) {
			// The rival is "Terry" in the ROM; a double battle names both trainers.
			const names = fight.name.replace(/^Rival$/, 'Terry').split(/ & /).map(n => n.split(' ').pop().toLowerCase());
			let best = null;
			let bestScore = 0;
			for (const variant of fight.variants) {
				const team = variant.sets.map(set => base(set.split(' (')[0]));
				for (const entry of entries) {
					const overlap = team.filter(s => entry.team.has(s)).length / Math.max(team.length, entry.team.size);
					const named = names.some(n => entry.name === n || entry.name.endsWith(n));
					const score = overlap + (named ? 1 : 0);
					if ((named ? overlap >= 0.3 : overlap >= 0.8) && score > bestScore) {
						bestScore = score;
						best = entry;
					}
				}
			}
			if (best) {
				out[mode][fight.name + '|' + fight.location + '|' + fight.levelCap] = best.flags;
				matched++;
			}
		}
		console.log(mode + ': ' + matched + ' of ' + order.length + ' fights matched');
	}
	fs.writeFileSync(OUTPUT, '/* Generated by import/radical-red-trainers/ai_flags.js from the Radical Red ROM; do not edit by\n' +
		' * hand. Each fight\'s AI flags by "name|location|level cap" (CFRU: 1 avoids bad moves, 7 also\n' +
		' * looks for good ones). Fights not listed use 7 if required, 1 if optional. */\n' +
		'var TRAINER_AI_FLAGS = ' + JSON.stringify(out) + ';\n');
}

if (process.argv.length < 3) {
	console.error('Usage: node import/radical-red-trainers/ai_flags.js <rom>');
	process.exit(1);
}
main(process.argv[2]);
