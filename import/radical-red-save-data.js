#!/usr/bin/env node
'use strict';
/*
 * Generates src/js/data/radical_red_save_data.js, the id -> name tables that
 * src/js/save_import.js needs to read a Pokémon Radical Red 4.1 .sav file.
 *
 * Usage (after `node build` so calc/dist exists):
 *   node import/radical-red-save-data.js <Rad-Red-4.1-Team-Exporter checkout> <pokeapi data/v2/csv dir>
 *
 * Sources:
 *  - https://github.com/eliyahu1702/Rad-Red-4.1-Team-Exporter: Species.txt, Moves.txt and
 *    Items.txt list the ROM's names in internal id order (line N = id N), and
 *    species_abilities.csv lists each species' two ability slots and hidden ability.
 *  - https://github.com/PokeAPI/pokeapi: pokemon_species.csv gives each species' growth
 *    rate, needed to turn a boxed Pokémon's EXP into a level.
 *
 * ROM names are truncated to fit the game's text boxes (e.g. "BrightPowder"), so every
 * name is matched to the calc's spelling by rom-names.js. Names the calc does not know
 * are dropped for moves and items, and kept as-is for abilities.
 */

const fs = require('fs');
const path = require('path');
const {calc, toKey, resolve} = require('./rom-names');

const OUTPUT = path.resolve(__dirname, '../src/js/data/radical_red_save_data.js');

function readLines(file) {
	return fs.readFileSync(file, 'utf8').split('\n').map(line => line.trim());
}

// Returns [unused id 0, name of id 1, name of id 2, ...] resolved to calc names.
function resolveTable(kind, romNames) {
	return [''].concat(romNames.map(name => resolve(kind, name) || ''));
}

function main(exporterDir, pokeapiDir) {
	const romSpecies = readLines(path.join(exporterDir, 'Species.txt'));
	// Formes the calc lacks (Unown letters) fall back to their base species.
	const species = [''].concat(romSpecies.map(name =>
		resolve('species', name) || resolve('species', name.split('-')[0]) || ''));

	const moves = resolveTable('move', readLines(path.join(exporterDir, 'Moves.txt')));
	const items = resolveTable('item', readLines(path.join(exporterDir, 'Items.txt')));

	const abilitiesByKey = {};
	for (const row of readLines(path.join(exporterDir, 'species_abilities.csv')).slice(1)) {
		if (!row) continue;
		const [name, ...slots] = row.split(',').map(cell => cell.trim());
		abilitiesByKey[toKey(name)] = slots.map(ability => {
			if (!ability) return '';
			return resolve('ability', ability, name) || ability;
		});
	}
	// The CSV spells some names differently (e.g. apostrophes), so match by key.
	const abilities = [null].concat(romSpecies.map(name =>
		abilitiesByKey[toKey(name)] || abilitiesByKey[toKey(name.split('-')[0])] || null));

	// PokeAPI growth_rate_id: 1 slow, 2 medium fast, 3 fast, 4 medium slow, 5 erratic,
	// 6 fluctuating. Formes use their base species' rate; 0 means unknown.
	const growthByKey = {};
	const speciesCsv = readLines(path.join(pokeapiDir, 'pokemon_species.csv'));
	const header = speciesCsv[0].split(',');
	const identifierCol = header.indexOf('identifier');
	const growthCol = header.indexOf('growth_rate_id');
	for (const row of speciesCsv.slice(1)) {
		if (!row) continue;
		const cells = row.split(',');
		growthByKey[toKey(cells[identifierCol])] = cells[growthCol];
	}
	const growthRates = species.map(name => {
		if (!name) return '0';
		const baseSpecies = calc.SPECIES[9][name].baseSpecies || name;
		return growthByKey[toKey(baseSpecies)] || growthByKey[toKey(baseSpecies.split('-')[0])] || '0';
	}).join('');

	const output = '/* Generated by import/radical-red-save-data.js; do not edit by hand.\n' +
		' * Radical Red 4.1 internal ids -> calc names, used by js/save_import.js. */\n' +
		'var RADICAL_RED_SAVE_DATA = ' + JSON.stringify({species, growthRates, abilities, moves, items}) + ';\n';
	fs.writeFileSync(OUTPUT, output);

	const report = (label, table) => console.log(label + ': ' + table.filter(Boolean).length + ' resolved');
	report('species', species);
	report('moves', moves);
	report('items', items);
	console.log('species without a growth rate: ' +
		species.filter((name, id) => name && growthRates[id] === '0').join(', '));
}

if (process.argv.length < 4) {
	console.error('Usage: node import/radical-red-save-data.js <exporter dir> <pokeapi csv dir>');
	process.exit(1);
}
main(process.argv[2], process.argv[3]);
