#!/usr/bin/env node
'use strict';
/*
 * Generates src/js/data/item_descriptions.js, what each held item does, for the ? beside the item
 * (src/js/item_info.js).
 *
 * Usage (after `node build` so calc/dist exists):
 *   node import/radical-red-item-descriptions.js <Pokémon Radical Red 4.1 ROM>
 *
 * Sources:
 *  - The ROM's own item descriptions, so Radical Red's changes show (e.g. Light Ball raising both
 *    attacking stats). Its item table is the FireRed layout (0x2C bytes an item: a 14-byte name,
 *    then id, price, hold effect and its parameter, then a pointer to the description), moved
 *    and grown by the hack: of the two tables whose item 1 is "Master Ball", FireRed's is first
 *    and the hack's last.
 *  - Pokémon Showdown's description (@pkmn/dex, MIT) for an item the ROM has no text for.
 *
 * ROM names are cut to fit the game's text boxes ("HvyDty Boots"), so they are matched to the
 * calc's spelling by rom-names.js.
 */

const fs = require('fs');
const path = require('path');
const {calc, resolve} = require('./rom-names');
const {Dex} = require('../calc/node_modules/@pkmn/dex');

const OUTPUT = path.resolve(__dirname, '../src/js/data/item_descriptions.js');
const ITEM_SIZE = 0x2C;
const ROM_BASE = 0x08000000;

// The game's character set (the part item names and descriptions use).
const CHARS = {
	0x00: ' ', 0x1B: 'é', 0x2D: '&', 0x2E: '+', 0x35: '=', 0x36: ';', 0x5B: '%', 0x5C: '(', 0x5D: ')',
	0xAB: '!', 0xAC: '?', 0xAD: '.', 0xAE: '-', 0xB0: '…', 0xB1: '“', 0xB2: '”', 0xB3: '‘', 0xB4: '’',
	0xB5: '♂', 0xB6: '♀', 0xB8: ',', 0xBA: '/', 0xF0: ':', 0xFE: '\n',
};
for (let i = 0; i < 26; i++) {
	CHARS[0xBB + i] = String.fromCharCode(65 + i);
	CHARS[0xD5 + i] = String.fromCharCode(97 + i);
}
for (let i = 0; i < 10; i++) CHARS[0xA1 + i] = String(i);

function decode(rom, offset, max) {
	let text = '';
	for (let i = 0; i < max && offset + i < rom.length; i++) {
		const byte = rom[offset + i];
		if (byte === 0xFF) break;
		text += CHARS[byte] !== undefined ? CHARS[byte] : '';
	}
	return text;
}

function encode(text) {
	const codes = {};
	Object.keys(CHARS).forEach(code => { codes[CHARS[code]] = +code; });
	return Buffer.from([...text].map(c => codes[c]).concat(0xFF));
}

function findItemTable(rom) {
	const at = rom.lastIndexOf(encode('Master Ball'));
	if (at === -1) throw new Error('No item table found: is this the Radical Red 4.1 ROM?');
	return at - ITEM_SIZE;
}

// "An item to be held by a Pokémon.\nThis headband ups Attack, but..." as one sentence or two.
function tidy(text) {
	return text.replace(/\s+/g, ' ').trim()
		.replace(/^An? (item|orb|hold item) to be held by (a )?Pokémon\. /, '')
		.replace(/^./, c => c.toUpperCase());
}

function main() {
	const rom = fs.readFileSync(process.argv[2]);
	const table = findItemTable(rom);
	const fromRom = {};
	for (let offset = table; offset + ITEM_SIZE <= rom.length; offset += ITEM_SIZE) {
		const pointer = rom.readUInt32LE(offset + 20);
		if (pointer < ROM_BASE || pointer >= ROM_BASE + rom.length) break;
		const name = resolve('item', decode(rom, offset, 14));
		const text = tidy(decode(rom, pointer - ROM_BASE, 400));
		if (name && text && !fromRom[name]) fromRom[name] = text;
	}
	const descriptions = {};
	let showdown = 0;
	calc.ITEMS[9].slice().sort().forEach(name => {
		if (fromRom[name]) {
			descriptions[name] = fromRom[name];
			return;
		}
		const item = Dex.items.get(name);
		const text = item.exists && (item.shortDesc || item.desc);
		if (text) {
			descriptions[name] = text;
			showdown++;
		}
	});
	fs.writeFileSync(OUTPUT,
		'/* What each held item does, for the ? beside the item (item_info.js). Radical Red\'s own text\n' +
		' * from the game\'s item descriptions where it has one, otherwise Pokémon Showdown\'s (@pkmn/dex,\n' +
		' * MIT). Generated by import/radical-red-item-descriptions.js; do not edit by hand. */\n' +
		'var ITEM_DESCRIPTIONS = ' + JSON.stringify(descriptions, null, '\t') + ';\n');
	console.log(`${Object.keys(descriptions).length} items: ${Object.keys(fromRom).length} from the ROM, ${showdown} from Showdown`);
}

main();
