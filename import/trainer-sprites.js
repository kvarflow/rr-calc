#!/usr/bin/env node
/*
 * Trainer sprites: picks a picture for every trainer in the trainer files (src/js/data/trainers/)
 * from Smogon's sprite archive (github.com/smogon/sprites, where Professor Oak's comes from) and
 * writes src/js/data/trainer_sprites.js.
 *
 * Trainers are known by the label their sets carry ("Leader Bugsy", "Youngster Timmy", "PkMn
 * Trainer Brendan"; " Set 2" and the like dropped). A trainer gets the sprite of their own name if
 * the archive has one (gym leaders, rivals, Brendan), else their class's (Youngster, Lass, Biker),
 * preferring FireRed / LeafGreen's art, then the other games nearest to it. Radical Red's own
 * trainers that no game has get none, and the panel shows no picture for them.
 *
 * Usage: node trainer-sprites.js <smogon/sprites checkout>
 *   (only src/_uncategorized/canonical/trainers is needed: a sparse checkout of it is enough)
 */
'use strict';

const fs = require('fs');
const path = require('path');
const {execSync} = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const TRAINERS_DIR = 'src/_uncategorized/canonical/trainers';
// Nearest to Radical Red's FireRed look first.
const GAMES = [
	'gen3/firered-leafgreen', 'gen4/heartgold-soulsilver', 'gen3/emerald', 'gen3/ruby-sapphire',
	'gen4/platinum', 'gen4/diamond-pearl', 'gen5/black2-white2', 'gen5/black-white',
	'gen2/crystal', 'gen2/gold-silver', 'gen1/yellow', 'gen1/red-blue',
];
// Radical Red's class names that the archive spells another way.
const CLASS_ALIASES = {
	'Ace Trainer': 'Cooltrainer',
	'Pokemaniac': 'Poke__0301_Maniac',
	'Rival': 'Blue',
	'Rocket Admin': 'Team_Rocket_Grunt',
	'Black Belt': 'Blackbelt',
	'SwimmerF': 'Swimmer~F',
	'SwimmerM': 'Swimmer',
	'Sis And Bro': 'Sis_and_Bro',
	'PkMn Breeder': 'Poke__0301mon_Breeder~F',
	'PkMn Ranger': 'Poke__0301mon_Ranger',
};
// Classes of named characters, who get their own picture when the archive has it. Everyone else
// (Youngster Timmy, Ace Trainer Lucy) gets their class's, even if some character shares the name.
const NAMED_CLASSES = /^(Leader|Elite Four|Champion|Rival|PkMn Trainer|Rocket Admin|Boss|Professor)\b/;
// Classes whose label is all class, no name ("Team Rocket Grunt").
const NAMELESS = /^(Team Rocket Grunt)$/;

function main() {
	const checkout = process.argv[2];
	if (!checkout) {
		console.error('Usage: node trainer-sprites.js <smogon/sprites checkout>');
		process.exit(1);
	}
	const commit = execSync('git rev-parse HEAD', {cwd: checkout}).toString().trim();
	const files = new Set();
	for (const game of GAMES) {
		const dir = path.join(checkout, TRAINERS_DIR, game);
		if (!fs.existsSync(dir)) continue;
		for (const file of fs.readdirSync(dir)) if (file.endsWith('.png')) files.add(game + '/' + file);
	}

	const labels = new Set();
	for (const file of fs.readdirSync(path.join(ROOT, 'src/js/data/trainers'))) {
		const source = fs.readFileSync(path.join(ROOT, 'src/js/data/trainers', file), 'utf8');
		for (const match of source.matchAll(/"[^"(]+ \(\*?([^)"]+)\)"/g)) labels.add(trainerLabel(match[1]));
	}

	const sprites = {};
	const missing = [];
	for (const label of [...labels].sort()) {
		const sprite = findSprite(label, files);
		if (sprite) sprites[label] = sprite;
		else missing.push(label);
	}

	const out = '/* Generated by import/trainer-sprites.js from smogon/sprites ' + commit.slice(0, 7) +
		'; do not edit by hand.\n' +
		' * A picture for each trainer (by the label their sets carry, without " Set N"), under\n' +
		' * TRAINER_SPRITE_BASE. Trainers missing here have none. */\n' +
		'var TRAINER_SPRITE_BASE = "https://raw.githubusercontent.com/smogon/sprites/' + commit + '/' + TRAINERS_DIR + '/";\n' +
		'var TRAINER_SPRITES = ' + JSON.stringify(sprites, null, '\t') + ';\n';
	fs.writeFileSync(path.join(ROOT, 'src/js/data/trainer_sprites.js'), out);
	console.log(Object.keys(sprites).length + ' of ' + labels.size + ' trainers have a sprite.');
	if (missing.length) console.log('None for: ' + missing.join(', '));
}

/** "Leader Bugsy Set 1" -> "Leader Bugsy". */
function trainerLabel(setName) {
	return setName.replace(/ Set \d+$/, '').trim();
}

function fileName(words) {
	return words.join('_') + '.png';
}

/** The first of `names` the archive has, in the order of GAMES. */
function firstIn(files, names) {
	for (const name of names) {
		for (const game of GAMES) {
			if (files.has(game + '/' + name)) return game + '/' + name;
		}
	}
	return null;
}

function findSprite(label, files) {
	const words = label.split(' ');
	if (NAMELESS.test(label)) return firstIn(files, [fileName(words)]);
	// A named character's own picture: the last word of the label, or the last two ("Lt. Surge").
	const names = [];
	if (NAMED_CLASSES.test(label)) {
		// A champion in their champion's outfit where the archive has one ("Blue-Champion").
		if (words[0] === 'Champion') names.push(words.slice(1).join('_') + '-Champion.png');
		for (let n = Math.min(2, words.length - 1); n >= 1; n--) names.push(fileName(words.slice(-n)));
	}
	if (words.length === 1) names.push(fileName(words));
	// Then their class: the words before the name ("Twins Eli & Anne": before "Eli & Anne"), as the
	// archive spells it.
	const pair = words.indexOf('&');
	const trainerClass = words.slice(0, pair > 0 ? pair - 1 : -1).join(' ');
	const classNames = [];
	if (CLASS_ALIASES[trainerClass]) classNames.push(CLASS_ALIASES[trainerClass] + '.png');
	if (trainerClass) classNames.push(fileName(trainerClass.split(' ')));
	return firstIn(files, names) || firstIn(files, classNames);
}

main();
