#!/usr/bin/env node
/*
 * Item icons: matches every item the calculator knows (all generations) to an icon in PokeAPI's
 * sprite set (github.com/PokeAPI/sprites, CC0; the art is The Pokémon Company's) and writes
 * src/js/data/item_icons.js. Items with no icon (Radical Red's own Mega Stones, Mail) get none.
 *
 * The icons themselves are copied into src/img/items by import/vendor-images.sh (run it after this).
 *
 * Usage: node item-icons.js <PokeAPI/sprites checkout>
 *   (only sprites/items is needed: a sparse checkout of it is enough)
 */
'use strict';

const fs = require('fs');
const path = require('path');
const {execSync} = require('child_process');
const calc = require('../calc/dist/index.js');

const ROOT = path.resolve(__dirname, '..');
const ITEMS_DIR = 'sprites/items';

/** "King's Rock" -> "kings-rock", "Never-Melt Ice" -> "never-melt-ice". */
function slug(name) {
	return name.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
		.replace(/['’.]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function main() {
	const checkout = process.argv[2];
	if (!checkout) {
		console.error('Usage: node item-icons.js <PokeAPI/sprites checkout>');
		process.exit(1);
	}
	const commit = execSync('git rev-parse HEAD', {cwd: checkout}).toString().trim();
	const files = new Set(fs.readdirSync(path.join(checkout, ITEMS_DIR)));
	const names = new Set();
	for (let gen = 1; gen <= 9; gen++) {
		for (const item of calc.Generations.get(gen).items) names.add(item.name);
	}
	const icons = {};
	const missing = [];
	for (const name of [...names].sort()) {
		// Z-Crystals' icons are named for the held crystal ("normalium-z--held").
		const file = [slug(name) + '.png', slug(name) + '--held.png'].find(f => files.has(f));
		if (file) icons[name] = file;
		else missing.push(name);
	}
	const out = '/* Generated by import/item-icons.js from PokeAPI/sprites ' + commit.slice(0, 7) +
		'; do not edit by hand.\n' +
		' * An icon for each item, under ITEM_ICON_BASE. Items missing here have none. */\n' +
		'var ITEM_ICON_BASE = "./img/items/";\n' +
		'var ITEM_ICONS = ' + JSON.stringify(icons, null, '\t') + ';\n';
	fs.writeFileSync(path.join(ROOT, 'src/js/data/item_icons.js'), out);
	console.log(Object.keys(icons).length + ' of ' + names.size + ' items have an icon.');
	if (missing.length) console.log('None for: ' + missing.join(', '));
}

main();
